-- ERA - PostgreSQL schema (used on Neon / Vercel). Same tables and business rules as ERA_database.sql (MySQL).
-- Safe to run more than once. Identifiers are unquoted (PostgreSQL stores them in lowercase);
-- "date" and "time" are quoted because they are type names.

CREATE TABLE IF NOT EXISTS Customer (
  userID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fullName VARCHAR(100) NOT NULL CHECK (CHAR_LENGTH(TRIM(fullName)) > 0),
  username VARCHAR(50) NOT NULL UNIQUE,
  email VARCHAR(255) NOT NULL UNIQUE,
  passwordHash VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS ServiceProvider (
  userID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fullName VARCHAR(100) NOT NULL CHECK (CHAR_LENGTH(TRIM(fullName)) > 0),
  username VARCHAR(50) NOT NULL UNIQUE,
  email VARCHAR(255) NOT NULL UNIQUE,
  passwordHash VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS Activity (
  activityID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  providerID INTEGER NOT NULL REFERENCES ServiceProvider(userID) ON DELETE RESTRICT,
  activityName VARCHAR(150) NOT NULL CHECK (CHAR_LENGTH(TRIM(activityName)) > 0),
  type VARCHAR(20) NOT NULL CHECK (type IN ('Sport', 'Wellness', 'Entertainment')),
  description TEXT NOT NULL,
  destination VARCHAR(100) NOT NULL,
  location VARCHAR(255) NOT NULL,
  "date" DATE NOT NULL,
  "time" TIME NOT NULL,
  availableCapacity INTEGER NOT NULL CHECK (availableCapacity >= 0),
  image VARCHAR(500),
  imageAlt VARCHAR(255),
  isDeleted BOOLEAN NOT NULL DEFAULT FALSE,
  stampShape VARCHAR(20),
  stampColor VARCHAR(20),
  stampIcon VARCHAR(30)
);
CREATE INDEX IF NOT EXISTS idx_activity_visible ON Activity (isDeleted, "date", type);
CREATE INDEX IF NOT EXISTS idx_activity_provider ON Activity (providerID);

CREATE TABLE IF NOT EXISTS Booking (
  bookingID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customerID INTEGER NOT NULL REFERENCES Customer(userID) ON DELETE RESTRICT,
  activityID INTEGER NOT NULL REFERENCES Activity(activityID) ON DELETE RESTRICT,
  bookingDate DATE NOT NULL DEFAULT CURRENT_DATE,
  status VARCHAR(10) NOT NULL DEFAULT 'Confirmed' CHECK (status IN ('Confirmed', 'Completed'))
);
CREATE INDEX IF NOT EXISTS idx_booking_activity_status ON Booking (activityID, status);
CREATE INDEX IF NOT EXISTS idx_booking_customer ON Booking (customerID);

CREATE TABLE IF NOT EXISTS DigitalTicket (
  ticketID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bookingID INTEGER NOT NULL UNIQUE REFERENCES Booking(bookingID) ON DELETE RESTRICT,
  ticketCode VARCHAR(100) NOT NULL UNIQUE,
  issuedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS DigitalActivityPassport (
  passportID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customerID INTEGER NOT NULL UNIQUE REFERENCES Customer(userID) ON DELETE RESTRICT,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS DigitalStamp (
  stampID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  passportID INTEGER NOT NULL REFERENCES DigitalActivityPassport(passportID) ON DELETE CASCADE,
  bookingID INTEGER NOT NULL UNIQUE REFERENCES Booking(bookingID) ON DELETE RESTRICT,
  awardedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_stamp_passport ON DigitalStamp (passportID);

CREATE TABLE IF NOT EXISTS Upload (
  uploadID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mime VARCHAR(30) NOT NULL,
  data BYTEA NOT NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ── Business rules (same as the MySQL triggers) ──

-- Creating a customer automatically creates exactly one passport.
CREATE OR REPLACE FUNCTION era_customer_create_passport() RETURNS trigger AS $$
BEGIN
  INSERT INTO DigitalActivityPassport (customerID) VALUES (NEW.userID);
  RETURN NEW;
END $$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_customer_create_passport ON Customer;
CREATE TRIGGER trg_customer_create_passport AFTER INSERT ON Customer
  FOR EACH ROW EXECUTE FUNCTION era_customer_create_passport();

-- A provider cannot soft-delete an activity with any Confirmed booking.
CREATE OR REPLACE FUNCTION era_activity_no_delete_if_booked() RETURNS trigger AS $$
BEGIN
  IF OLD.isDeleted = FALSE AND NEW.isDeleted = TRUE AND EXISTS (
    SELECT 1 FROM Booking b WHERE b.activityID = OLD.activityID AND b.status = 'Confirmed'
  ) THEN
    RAISE EXCEPTION 'Cannot delete an activity with active bookings.';
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_activity_no_delete_if_booked ON Activity;
CREATE TRIGGER trg_activity_no_delete_if_booked BEFORE UPDATE ON Activity
  FOR EACH ROW EXECUTE FUNCTION era_activity_no_delete_if_booked();

-- A booking reserves exactly ONE remaining seat.
CREATE OR REPLACE FUNCTION era_booking_reserve_one_seat() RETURNS trigger AS $$
BEGIN
  IF NEW.status <> 'Confirmed' THEN
    RAISE EXCEPTION 'A new booking must start as Confirmed.';
  END IF;
  UPDATE Activity SET availableCapacity = availableCapacity - 1
    WHERE activityID = NEW.activityID AND isDeleted = FALSE AND availableCapacity > 0;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Activity unavailable or fully booked.';
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_booking_reserve_one_seat ON Booking;
CREATE TRIGGER trg_booking_reserve_one_seat BEFORE INSERT ON Booking
  FOR EACH ROW EXECUTE FUNCTION era_booking_reserve_one_seat();

-- Each booking generates ONE digital ticket.
CREATE OR REPLACE FUNCTION era_booking_create_ticket() RETURNS trigger AS $$
BEGIN
  INSERT INTO DigitalTicket (bookingID, ticketCode)
  VALUES (NEW.bookingID, 'ERA-' || UPPER(SUBSTR(MD5(RANDOM()::text || CLOCK_TIMESTAMP()::text || NEW.bookingID::text), 1, 24)));
  RETURN NEW;
END $$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_booking_create_ticket ON Booking;
CREATE TRIGGER trg_booking_create_ticket AFTER INSERT ON Booking
  FOR EACH ROW EXECUTE FUNCTION era_booking_create_ticket();

-- A stamp needs a Completed booking and that customer's passport.
CREATE OR REPLACE FUNCTION era_stamp_validate_owner() RETURNS trigger AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM Booking b JOIN DigitalActivityPassport p ON p.customerID = b.customerID
    WHERE b.bookingID = NEW.bookingID AND b.status = 'Completed' AND p.passportID = NEW.passportID
  ) THEN
    RAISE EXCEPTION 'Stamp requires a completed booking and its customer passport.';
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_stamp_validate_owner ON DigitalStamp;
CREATE TRIGGER trg_stamp_validate_owner BEFORE INSERT ON DigitalStamp
  FOR EACH ROW EXECUTE FUNCTION era_stamp_validate_owner();

-- Confirmed -> Completed automatically awards one digital stamp.
CREATE OR REPLACE FUNCTION era_booking_award_stamp() RETURNS trigger AS $$
BEGIN
  IF OLD.status = 'Confirmed' AND NEW.status = 'Completed' THEN
    INSERT INTO DigitalStamp (passportID, bookingID)
    SELECT p.passportID, NEW.bookingID FROM DigitalActivityPassport p WHERE p.customerID = NEW.customerID;
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_booking_award_stamp ON Booking;
CREATE TRIGGER trg_booking_award_stamp AFTER UPDATE ON Booking
  FOR EACH ROW EXECUTE FUNCTION era_booking_award_stamp();
